"""Write the studio's words.ts (word start/end frames at 30 fps) from words.json.

Run after every new take (temp Daniel take now; the real Gvd9RXquQXWjTYwBivjq take later):
  python sync_words.py
story.ts anchors every cut and reaction to a WORD INDEX, so as long as script_tts.txt is unchanged the whole
picture re-times itself to the new take. Afterwards: re-run the audio script (mix.wav) and re-render.
"""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = Path("B:/Projects/Youtube/shorts-studio/src/videos/blackout_p01/words.ts")

w = json.loads((HERE / "words.json").read_text(encoding="utf-8"))
starts = [round(x["start"] * 30) for x in w]
ends = [round(x["end"] * 30) for x in w]
lines = [
    "// GENERATED by series/01-blackout/part-01/voice/sync_words.py from words.json - do not edit by hand.",
    f"// {len(w)} words: " + " ".join(f"{i}:{x['word']}" for i, x in enumerate(w)),
    f"export const WS: number[] = {json.dumps(starts)};",
    f"export const WE: number[] = {json.dumps(ends)};",
    "",
]
OUT.write_text("\n".join(lines), encoding="utf-8")
print(f"{OUT}: {len(w)} words, last ends at frame {ends[-1]}")
